"""Run the evaluation: baseline (no retrieval) vs RAG, plus the proof notebook's answers re-scored.

Builds a fresh index from data/corpus in a temporary folder (your own chroma_db is not
touched), asks every question in eval/questions.json both ways, and writes eval/results.md
and eval/results.json.

Usage:
  python -m eval.run_eval
"""

import argparse
import json
import platform
import statistics
import subprocess
import tempfile
import time
from dataclasses import asdict, replace
from datetime import UTC, datetime
from pathlib import Path

from rag.config import Settings
from rag.embeddings import SentenceTransformerEmbedder
from rag.evaluation import (
    EvalQuestion,
    Grade,
    grade,
    load_questions,
    retrieval_hit,
    tally,
)
from rag.generator import HuggingFaceGenerator
from rag.loader import SUPPORTED_SUFFIXES
from rag.logs import configure_logging
from rag.pipeline import RagPipeline
from rag.store import ChromaStore

ROOT = Path(__file__).resolve().parent.parent
HIT_KS = (1, 3, 5)
SETS = ("benchmark", "held_out")
SET_TITLES = {"benchmark": "Benchmark (notebook questions)", "held_out": "Held-out (new)"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--questions", type=Path, default=ROOT / "eval/questions.json")
    parser.add_argument("--notebook", type=Path, default=ROOT / "eval/notebook_answers.json")
    parser.add_argument("--corpus", type=Path, default=ROOT / "data/corpus")
    parser.add_argument("--out", type=Path, default=ROOT / "eval/results.md")
    args = parser.parse_args()

    settings = Settings.from_env()
    configure_logging("WARNING")
    questions = load_questions(args.questions)
    notebook = json.loads(args.notebook.read_text(encoding="utf-8"))["answers"]

    with tempfile.TemporaryDirectory() as tmp:
        settings = replace(settings, chroma_dir=Path(tmp) / "chroma", collection="eval")
        generator = HuggingFaceGenerator(settings.gen_model, settings.max_new_tokens)
        pipeline = RagPipeline(
            SentenceTransformerEmbedder(settings.embed_model),
            ChromaStore(settings.chroma_dir, settings.collection),
            generator,
            chunk_size=settings.chunk_size,
            chunk_overlap=settings.chunk_overlap,
            top_k=settings.top_k,
        )
        files = sorted(p for p in args.corpus.iterdir() if p.suffix.lower() in SUPPORTED_SUFFIXES)
        for path in files:
            pipeline.ingest(path)
        rows = [evaluate(q, pipeline, settings.top_k, notebook.get(q.id)) for q in questions]

    run = {
        "date": datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
        "commit": git_commit(),
        "generator": generator.description,
        "embedder": settings.embed_model,
        "machine": f"{platform.system()} {platform.machine()}",
        "chunk_size": settings.chunk_size,
        "chunk_overlap": settings.chunk_overlap,
        "top_k": settings.top_k,
        "max_new_tokens": settings.max_new_tokens,
        "chunks_indexed": pipeline.chunk_count(),
        "corpus_files": [p.name for p in files],
    }
    args.out.write_text(render_markdown(run, rows), encoding="utf-8")
    args.out.with_suffix(".json").write_text(
        json.dumps({"run": run, "rows": rows}, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print(f"Wrote {args.out.relative_to(ROOT)} and {args.out.with_suffix('.json').name}")


def evaluate(
    q: EvalQuestion, pipeline: RagPipeline, top_k: int, notebook: dict[str, str] | None
) -> dict:
    """Ask one question both ways and grade everything."""
    hits = pipeline.retrieve(q.question, max(HIT_KS))

    t0 = time.perf_counter()
    rag = pipeline.ask(q.question, top_k=top_k)
    rag_seconds = time.perf_counter() - t0

    t0 = time.perf_counter()
    baseline = pipeline.ask(q.question, use_rag=False)
    baseline_seconds = time.perf_counter() - t0

    row = {
        "question": asdict(q),
        "hits": {f"hit@{k}": retrieval_hit(hits, q, k) for k in HIT_KS},
        "retrieved": [f"{h.source}#{h.chunk} ({h.score:.2f})" for h in hits],
        "rag": {"answer": rag.text, "grade": grade(rag.text, q), "seconds": rag_seconds},
        "baseline": {
            "answer": baseline.text,
            "grade": grade(baseline.text, q),
            "seconds": baseline_seconds,
        },
        "notebook": None,
    }
    if notebook:
        row["notebook"] = {
            "rag": {"answer": notebook["rag"], "grade": grade(notebook["rag"], q)},
            "baseline": {"answer": notebook["baseline"], "grade": grade(notebook["baseline"], q)},
        }
    return row


def render_markdown(run: dict, rows: list[dict]) -> str:
    lines = [
        "# Evaluation results",
        "",
        "Generated by `python -m eval.run_eval`. Do not edit by hand; re-run instead.",
        "",
        "## Run",
        "",
        "| Setting | Value |",
        "|---|---|",
        f"| Date | {run['date']} |",
        f"| Commit | `{run['commit']}` |",
        f"| Generator | {run['generator']} |",
        f"| Embedder | {run['embedder']} |",
        f"| Machine | {run['machine']} |",
        f"| Chunks | {run['chunk_size']} chars, {run['chunk_overlap']} overlap, "
        f"{run['chunks_indexed']} chunks from {len(run['corpus_files'])} files |",
        f"| Retrieval | top {run['top_k']} for answers; hit@1/3/5 measured separately |",
        f"| Decoding | greedy, up to {run['max_new_tokens']} new tokens |",
        "",
        "## Answer correctness",
        "",
        "| Question set | Mode | Correct | Partial | Refused | Wrong |",
        "|---|---|---|---|---|---|",
    ]
    for s in SETS:
        subset = [r for r in rows if r["question"]["set"] == s]
        if not subset:
            continue
        modes = [("No retrieval (baseline)", "baseline"), ("RAG", "rag")]
        for label, mode in modes:
            counts = tally([r[mode]["grade"] for r in subset])
            lines.append(
                f"| {SET_TITLES[s]} | {label} | "
                + " | ".join(f"{counts[g]}/{len(subset)}" for g in Grade)
                + " |"
            )
        scored = [r for r in subset if r["notebook"]]
        if scored:
            for label, mode in [
                ("Notebook baseline, re-scored", "baseline"),
                ("Notebook RAG, re-scored", "rag"),
            ]:
                counts = tally([r["notebook"][mode]["grade"] for r in scored])
                lines.append(
                    f"| {SET_TITLES[s]} | {label} | "
                    + " | ".join(f"{counts[g]}/{len(scored)}" for g in Grade)
                    + " |"
                )

    lines += [
        "",
        "## Retrieval",
        "",
        "Share of answerable questions where a chunk from the expected file containing the "
        "evidence text was in the top k.",
        "",
        "| Question set | " + " | ".join(f"hit@{k}" for k in HIT_KS) + " |",
        "|---|" + "---|" * len(HIT_KS),
    ]
    for s in SETS:
        subset = [r for r in rows if r["question"]["set"] == s and r["hits"]["hit@1"] is not None]
        if subset:
            cells = [f"{sum(r['hits'][f'hit@{k}'] for r in subset)}/{len(subset)}" for k in HIT_KS]
            lines.append(f"| {SET_TITLES[s]} | " + " | ".join(cells) + " |")

    rag_times = [r["rag"]["seconds"] for r in rows]
    base_times = [r["baseline"]["seconds"] for r in rows]
    lines += [
        "",
        "## Latency",
        "",
        f"Median seconds per answer (model already loaded): RAG {statistics.median(rag_times):.1f}"
        f" s, baseline {statistics.median(base_times):.1f} s.",
        "",
        "## Per question",
        "",
        "| Set | Question | hit@3 | Baseline | RAG | Notebook RAG |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        q = r["question"]
        hit = r["hits"]["hit@3"]
        nb = r["notebook"]["rag"]["grade"] if r["notebook"] else "-"
        lines.append(
            f"| {q['set']} | {q['question']} | {'-' if hit is None else ('yes' if hit else 'no')}"
            f" | {r['baseline']['grade']} | {r['rag']['grade']} | {nb} |"
        )

    lines += ["", "## Answers", ""]
    for r in rows:
        q = r["question"]
        lines += [
            f"### {q['question']}",
            "",
            f"- Set: {q['set']}. Key facts: {one_line(q['key_facts']) or 'refusal expected'}."
            + (f" Note: {q['note']}" if q["note"] else ""),
            f"- Retrieved (top 5): {', '.join(r['retrieved'])}",
            f"- **RAG ({r['rag']['grade']}, {r['rag']['seconds']:.1f} s):** "
            f"{one_line(r['rag']['answer'])}",
            f"- **Baseline ({r['baseline']['grade']}):** {one_line(r['baseline']['answer'])}",
        ]
        if r["notebook"]:
            lines.append(
                f"- **Notebook RAG ({r['notebook']['rag']['grade']}):** "
                f"{one_line(r['notebook']['rag']['answer'])}"
            )
        lines.append("")
    return "\n".join(lines)


def one_line(value: object) -> str:
    text = value if isinstance(value, str) else json.dumps(value)
    return " ".join(text.split()).replace("|", "\\|")


def git_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT
        )
        return out.stdout.strip() or "unknown"
    except OSError:
        return "unknown"


if __name__ == "__main__":
    main()
